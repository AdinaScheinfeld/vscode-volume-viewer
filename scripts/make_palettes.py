"""Generate src/palettes.ts: six label palettes of 150 colors each.

Each palette owns its own region of OKLCH color space (a hue family and a lightness band),
and the regions do not overlap, so two label files never share a color. Within a palette,
colors are picked by farthest-point sampling, so low label numbers are the most separated.

Usage: make_palettes.py OUT_TS OUT_PREVIEW_PNG
"""
import sys

import numpy as np
from PIL import Image, ImageDraw

N = 150
# name, hue range in degrees (start, end, wrapping), lightness range
WARM, GREEN, COOL = (340, 100), (104, 190), (194, 336)
BRIGHT, DEEP = (0.64, 0.93), (0.34, 0.60)
# Candidates closer than this (OKLab) to a color in an earlier palette are dropped.
MIN_CROSS = 0.04
REGIONS = [
    ("Warm (bright)", WARM, BRIGHT),
    ("Cool (bright)", COOL, BRIGHT),
    ("Green (bright)", GREEN, BRIGHT),
    ("Warm (deep)", WARM, DEEP),
    ("Cool (deep)", COOL, DEEP),
    ("Green (deep)", GREEN, DEEP),
]


def oklch_to_linear(L, C, H):
    a = C * np.cos(np.radians(H))
    b = C * np.sin(np.radians(H))
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return np.stack([r, g, bl], axis=-1), np.stack([L, a, b], axis=-1)


def to_srgb8(lin):
    v = np.where(lin <= 0.0031308, 12.92 * lin, 1.055 * np.power(np.maximum(lin, 1e-12), 1 / 2.4) - 0.055)
    return np.clip(np.round(v * 255), 0, 255).astype(int)


def candidates(hue, light, c_min):
    Ls = np.arange(light[0], light[1] + 1e-9, 0.01)
    Cs = np.arange(c_min, 0.38, 0.01)
    h0, h1 = hue
    span = (h1 - h0) % 360
    Hs = (h0 + np.arange(0, span + 1e-9, 1.5)) % 360
    L, C, H = np.meshgrid(Ls, Cs, Hs, indexing="ij")
    L, C, H = L.ravel(), C.ravel(), H.ravel()
    lin, lab = oklch_to_linear(L, C, H)
    keep = np.all((lin >= 0) & (lin <= 1), axis=-1)
    return lab[keep], lin[keep], C[keep]


def farthest_points(lab, chroma, n):
    picked = [int(np.argmax(chroma))]
    d = np.linalg.norm(lab - lab[picked[0]], axis=1)
    for _ in range(n - 1):
        i = int(np.argmax(d))
        picked.append(i)
        d = np.minimum(d, np.linalg.norm(lab - lab[i], axis=1))
    return np.array(picked)


def min_pair(a):
    d = np.linalg.norm(a[:, None] - a[None, :], axis=-1)
    return d[np.triu_indices(len(a), 1)].min() * 100


out_ts, out_png = sys.argv[1], sys.argv[2]
labs, rgbs = [], []
for name, hue, light in REGIONS:
    lab, lin, chroma = candidates(hue, light, 0.07 if light == BRIGHT else 0.05)
    if labs:
        prev = np.concatenate(labs)
        near = np.zeros(len(lab), bool)
        for s in range(0, len(lab), 2000):
            d = np.linalg.norm(lab[s:s + 2000][:, None] - prev[None, :], axis=-1)
            near[s:s + 2000] = d.min(axis=1) < MIN_CROSS
        lab, lin, chroma = lab[~near], lin[~near], chroma[~near]
    idx = farthest_points(lab, chroma, N)
    labs.append(lab[idx])
    rgbs.append(to_srgb8(lin[idx]))
    print(f"{name:16s} candidates={len(lab):7d}  min distance: all150={min_pair(lab[idx]):.2f}"
          f"  first50={min_pair(lab[idx][:50]):.2f}  first20={min_pair(lab[idx][:20]):.2f}"
          f"  first10={min_pair(lab[idx][:10]):.2f}")

worst = min(
    np.linalg.norm(labs[i][:, None] - labs[j][None, :], axis=-1).min() * 100
    for i in range(len(labs)) for j in range(i + 1, len(labs))
)
print(f"closest pair across any two palettes: {worst:.2f} (OKLab x100; about 2 is barely visible)")
all_hex = {tuple(c) for p in rgbs for c in p}
print(f"unique colors: {len(all_hex)} of {N * len(rgbs)}")

with open(out_ts, "w") as f:
    f.write("// Generated by scripts/make_palettes.py. Do not edit by hand.\n")
    f.write("// Six label palettes, 150 colors each, stored as concatenated RRGGBB.\n\n")
    f.write("export const PALETTE_DATA: { name: string; hex: string }[] = [\n")
    for (name, _, _), p in zip(REGIONS, rgbs):
        hx = "".join(f"{r:02x}{g:02x}{b:02x}" for r, g, b in p)
        f.write(f"  {{ name: {name!r}, hex: '{hx}' }},\n")
    f.write("];\n")

# Preview: one row per palette, on black and on mid-gray.
cell, cols = 16, 75
W, H = cols * cell + 150, (2 * cell + 10) * len(rgbs) + 10
im = Image.new("RGB", (W, H), (30, 30, 30))
dr = ImageDraw.Draw(im)
for i, ((name, _, _), p) in enumerate(zip(REGIONS, rgbs)):
    y0 = 10 + i * (2 * cell + 10)
    dr.text((6, y0 + 8), name, fill=(230, 230, 230))
    for k, c in enumerate(p):
        x, y = 150 + (k % cols) * cell, y0 + (k // cols) * cell
        dr.rectangle((x, y, x + cell - 1, y + cell - 1), fill=tuple(int(v) for v in c))
im.save(out_png)
print("wrote", out_ts, "and", out_png)
